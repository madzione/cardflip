#!/usr/bin/env bash
# Runs the end-to-end flow in Chrome against the Go core compiled to
# WebAssembly, with the collection in IndexedDB (task 12.2).
#
#   tool/web_integration.sh            # headless
#   HEADED=1 tool/web_integration.sh   # with a visible browser window
#
# Needs chromedriver matching the installed Chrome/Chromium on PATH.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
export PATH="$HOME/go/bin:$PATH"
cd "$root"

# The browser cannot read the fixture from disk; embed its bytes. The file is
# committed so the project analyzes cleanly; this keeps it current.
fixture=golang/importer/apkg/testdata/modern.apkg
{
  echo "// Generated by tool/web_integration.sh from $fixture. Do not edit."
  echo "const modernApkgBase64 ="
  base64 -w0 "$fixture" | sed "s/.*/    '&';/"
} > integration_test/fixture.g.dart

fluffy lib web

if [[ -z "${CHROME_EXECUTABLE:-}" ]] && ! command -v google-chrome >/dev/null; then
  export CHROME_EXECUTABLE="$(command -v chromium || true)"
fi

port=4444
chromedriver --port=$port >/dev/null 2>&1 &
driver=$!
trap 'kill $driver 2>/dev/null' EXIT
sleep 1

browser_flags=(--web-browser-flag=--no-sandbox --web-browser-flag=--window-size=1280,900)
if [[ -z "${HEADED:-}" ]]; then
  browser_flags+=(--headless)
fi
fvm flutter drive \
  --driver test_driver/integration_test.dart \
  --target integration_test/app_flow_web.dart \
  -d web-server --browser-name=chrome --driver-port=$port \
  "${browser_flags[@]}"

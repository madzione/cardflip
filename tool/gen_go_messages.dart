// Generates lib/l10n/go_messages.dart from lib/l10n/app_en.arb: for every
// message whose key starts with "go", a function that makes it from the
// arguments of a tagged Go text (see lib/l10n/go_text.dart).
//
// Run it after adding a Go message to app_en.arb:
//
//	fvm dart run tool/gen_go_messages.dart
import 'dart:convert';
import 'dart:io';

const arbPath = 'lib/l10n/app_en.arb';
const outPath = 'lib/l10n/go_messages.dart';

void main() {
  File(outPath)
      .writeAsStringSync(goMessagesSource(File(arbPath).readAsStringSync()));
}

/// The Dart source of go_messages.dart for the English ARB file [arb].
String goMessagesSource(String arb) {
  final messages = jsonDecode(arb) as Map<String, Object?>;
  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/gen_go_messages.dart from $arbPath; do not edit.',
    )
    ..writeln()
    ..writeln("import 'app_localizations.dart';")
    ..writeln()
    ..writeln(
      '/// The messages of Go texts by code, made from their arguments.',
    )
    ..writeln('final goMessages =')
    ..writeln(
      '    <String, String Function(AppLocalizations l, List<String> a)>{',
    );
  final keys = messages.keys.where(isGoKey).toList()..sort();
  for (final key in keys) {
    final code = key[2].toLowerCase() + key.substring(3);
    final meta = messages['@$key'] as Map<String, Object?>? ?? const {};
    final placeholders =
        meta['placeholders'] as Map<String, Object?>? ?? const {};
    final args = [
      for (final (i, p) in placeholders.values.indexed)
        switch ((p as Map<String, Object?>)['type']) {
          'int' => 'int.parse(a[$i])',
          'double' || 'num' => 'double.parse(a[$i])',
          _ => 'a[$i]',
        },
    ];
    final call = args.isEmpty ? 'l.$key' : 'l.$key(${args.join(', ')})';
    out.writeln("  '$code': (l, a) => $call,");
  }
  out.writeln('};');
  return out.toString();
}

/// Whether [key] is the key of a Go message, like "goDeckNameTaken".
bool isGoKey(String key) =>
    key.length > 2 &&
    key.startsWith('go') &&
    key[2].toUpperCase() == key[2] &&
    key[2].toLowerCase() != key[2];
